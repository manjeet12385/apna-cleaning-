function setAboutLanguage(language) {
  const messages = aboutMessages[language];
  document.documentElement.lang = language;
  document.title = messages.pageTitle;

  document.querySelectorAll("[data-about-copy]").forEach((element) => {
    element.textContent = messages[element.dataset.aboutCopy];
  });
  document.querySelectorAll("[data-about-content]").forEach((element) => {
    element.setAttribute("content", messages[element.dataset.aboutContent]);
  });
  document.querySelectorAll("[data-about-aria]").forEach((element) => {
    element.setAttribute("aria-label", messages[element.dataset.aboutAria]);
  });
  document.querySelectorAll("[data-about-language]").forEach((button) => {
    const isActive = button.dataset.aboutLanguage === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  localStorage.setItem("apna-cleaning-language", language);
}

document.querySelectorAll("[data-about-language]").forEach((button) => {
  button.addEventListener("click", () => setAboutLanguage(button.dataset.aboutLanguage));
});

const savedLanguage = localStorage.getItem("apna-cleaning-language");
setAboutLanguage(savedLanguage === "en" ? "en" : "hi");
document.querySelector("#about-year").textContent = new Date().getFullYear();
